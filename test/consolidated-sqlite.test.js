import test from './test-runtime.js';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtemp, mkdir, rm, stat } from 'node:fs/promises';
import { join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { tmpdir } from 'node:os';
import { SQLiteRelayStore, discoverLocalRelayStoreSnapshots } from '../dist/relay-store.js';
import { ProjectionOutbox } from '../dist/projection-outbox.js';
import { openLocalManagedStore } from '../dist/local-managed-store.js';
import { createJobIdRegistryResolver } from '../dist/local-job-registry.js';
import { ensureManagedGitHubJob } from '../dist/cli-job-create.js';
import { allocateEntityId } from '../dist/job-task-id-sequence.js';
// Legacy path names are test fixtures for the explicit offline migration tool only.
const relayStorePath = (directory, repository, pr) => join(directory, repository.replace('/', '_')+'-'+pr+'.db');
const relayJobStorePath = (directory, id) => join(directory, 'job-'+id+'.db');

test('single SQLite consolidation preserves independent Job records, outboxes and global sequences', async () => {
  const root = await mkdtemp(join(tmpdir(),'relay-unified-'));
  const source = join(root,'stores');
  const target = join(root,'relay.sqlite');
  await mkdir(source);
  try {
    const a = new SQLiteRelayStore(relayStorePath(source,'example/first',9));
    const b = new SQLiteRelayStore(relayJobStorePath(source,'2'));
    const createdAt='2026-10-14T00:00:00.000Z';
    const makeJob=(id,repository,prNumber)=>({id,title:`Job ${id}`,repository,prNumber,objective:'fixture',state:'COMPLETED',continuation:null,createdAt,updatedAt:createdAt,tasks:[{id:'1',jobId:id,state:'SUCCEEDED'}],plans:[]});
    await a.saveJob(makeJob('1','example/first',9));
    await b.saveJob(makeJob('2','example/second',0));
    await a.enqueueProjection({idempotencyKey:'same-key',operation:'save_job',payload:{jobId:'1'}});
    await b.enqueueProjection({idempotencyKey:'same-key',operation:'save_job',payload:{jobId:'2'}});
    a.close(); b.close();
    // Empty legacy DB shells may exist from attempted Job opens; they must not be treated as Jobs.
    const shellOnly = new SQLiteRelayStore(relayJobStorePath(source,'ghost'));
    shellOnly.close();
    // This test alone constructs an explicit legacy migration input, including its old global sequence file.
    const legacySequences = new DatabaseSync(join(source, 'entity-id-sequences.sqlite'));
    legacySequences.exec('CREATE TABLE sequences (repository TEXT NOT NULL,kind TEXT NOT NULL,value INTEGER NOT NULL,PRIMARY KEY(repository,kind)); CREATE TABLE idempotency (repository TEXT NOT NULL,kind TEXT NOT NULL,request_key TEXT NOT NULL,entity_id TEXT NOT NULL,PRIMARY KEY(repository,kind,request_key))');
    legacySequences.prepare('INSERT INTO sequences VALUES (?,?,?)').run('*','job',2);
    legacySequences.close();
    const result = spawnSync('python3',['scripts/consolidate-relay-sqlite.py',source,target],{encoding:'utf8'});
    assert.equal(result.status,0,result.stderr);
    assert.equal(allocateEntityId(source,'example/first','job',undefined,new Set(['1','2'])),'3');
    const details=JSON.parse(result.stdout);
    assert.equal(details.jobs,2);
    assert.ok((await stat(target)).size>0);
    const db=new DatabaseSync(target,{readOnly:true});
    assert.deepEqual(db.prepare('SELECT job_id FROM source_registry ORDER BY job_id').all().map(x=>x.job_id),['1','2']);
    assert.equal(db.prepare('SELECT COUNT(*) as n FROM job_snapshot').get().n,2);
    assert.equal(db.prepare('SELECT COUNT(*) as n FROM projection_outbox').get().n,2);
    assert.equal(db.prepare('SELECT COUNT(*) as n FROM projection_outbox WHERE id=1').get().n,2);
    assert.equal(db.prepare('SELECT COUNT(*) as n FROM projection_outbox WHERE idempotency_key=?').get('same-key').n,2);
    assert.equal(db.prepare('PRAGMA integrity_check').get().integrity_check,'ok');
    db.close();
    const live = new DatabaseSync(target);
    const outA = new ProjectionOutbox(live,'1');
    const outB = new ProjectionOutbox(live,'2');
    assert.equal(outA.pendingCount(),1);
    assert.equal(outB.pendingCount(),1);
    const claimed=outA.claimDue(5,new Date());
    assert.equal(claimed.length,1);
    assert.equal(claimed[0].id,1);
    assert.equal(outA.pendingCount(),1);
    assert.equal(outB.pendingCount(),1);
    outA.completeWithReceipt(1,'same-key','succeeded',0,{ok:true},new Date().toISOString());
    assert.equal(outA.pendingCount(),0);
    assert.equal(outB.pendingCount(),1);
    live.exec('BEGIN IMMEDIATE');
    outB.enqueue({idempotencyKey:'next-key',operation:'save_job',payload:{jobId:'2'}},new Date().toISOString());
    live.exec('COMMIT');
    assert.equal(outB.pendingCount(),2);
    live.close();
    const scopedA = new SQLiteRelayStore(target,'1');
    const scopedB = new SQLiteRelayStore(target,'2');
    assert.equal((await scopedA.loadJob('1')).title,'Job 1');
    assert.equal((await scopedB.loadJob('2')).title,'Job 2');
    await assert.rejects(scopedA.loadJob('2'),/Wrong scoped Job ID/);
    assert.deepEqual((await scopedA.listJobs()).map(job=>job.id),['1']);
    assert.deepEqual((await scopedB.listJobs()).map(job=>job.id),['2']);
    await scopedA.savePullRequestFacts({state:'OPEN',head:null,observedAt:'2026-10-14T00:00:00Z'});
    await scopedB.savePullRequestFacts({state:'MERGED',head:null,observedAt:'2026-10-14T00:00:00Z'});
    assert.equal((await scopedA.loadPullRequestFacts()).state,'OPEN');
    assert.equal((await scopedB.loadPullRequestFacts()).state,'MERGED');
    assert.equal(await scopedA.markEventProcessed('same-event'),true);
    assert.equal(await scopedB.markEventProcessed('same-event'),true);
    assert.equal(await scopedA.markEventProcessed('same-event'),false);
    assert.equal(await scopedB.markEventProcessed('same-event'),false);
    await scopedA.saveAgents([]);
    assert.deepEqual(await scopedA.loadAgents(),[]);
    assert.equal(await scopedB.loadAgents(),null);
    const updated=await scopedB.mutateJob('2', job=>({...job,title:'Updated Job 2'}));
    assert.equal(updated.title,'Updated Job 2');
    assert.equal((await scopedA.loadJob('1')).title,'Job 1');
    assert.equal((await scopedB.loadJob('2')).title,'Updated Job 2');
    scopedA.close(); scopedB.close();
    {
      const inventory=await discoverLocalRelayStoreSnapshots(source);
      assert.deepEqual(inventory.map(item=>item.jobs[0].id),['1','2']);
      assert.equal(inventory[0].path,target);
      assert.equal(inventory[1].path,target);
      const opened=openLocalManagedStore('example/first',9,{directory:source});
      assert.equal((await opened.store.load('1')).title,'Job 1');
      opened.relay.close();
      const firstOnly=createJobIdRegistryResolver(source,new Map(),{noGitHub:true});
      const resolved=await firstOnly('2');
      assert.equal((await resolved.store.load('2')).title,'Updated Job 2');
      resolved.relay.close();
      const client={request:async()=>{throw Error('no GitHub')},graphql:async()=>{throw Error('no GitHub')}};
      const created=await ensureManagedGitHubJob(client,'example/third',new Set(),{title:'New unified job',objective:'unified',storeDirectory:source,idempotencyKey:'new-unified'});
      assert.equal(created.job.id,'4');
      assert.equal((await discoverLocalRelayStoreSnapshots(source)).length,3);
      const againCreated=await ensureManagedGitHubJob(client,'example/third',new Set(),{title:'New unified job',objective:'unified',storeDirectory:source,idempotencyKey:'new-unified'});
      assert.equal(againCreated.job.id,'4');
    }
    const again=spawnSync('python3',['scripts/consolidate-relay-sqlite.py',source,target],{encoding:'utf8'});
    assert.notEqual(again.status,0);
    assert.match(again.stderr,/Destination exists/);
  } finally {
    await rm(root,{recursive:true,force:true});
  }
});
